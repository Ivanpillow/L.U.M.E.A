const dicts: Record<Lang, Record<Key, string>> = { es, en };
let lang: Lang = "es";

export const getLang = (): Lang => lang;
export function setLang(l: Lang) { lang = l; }
export const keysOf = (l: Lang): string[] => Object.keys(dicts[l]);

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = dicts[lang][key] ?? dicts.es[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Texto opcional con clave dinámica (p. ej. nombres cortos por id de perfil). */
export function tOpt(key: string, fallback: string): string {
  return (dicts[lang] as Record<string, string>)[key] ?? fallback;
}

/** Traduce un texto que viene de los datos; si no hay traducción, devuelve el original. */
export function td(s: string): string {
  return lang === "es" ? dataEs[s] ?? s : s;
}

/** Decimales y miles según el idioma. */
export function num(x: number, digits = 0): string {
  return x.toLocaleString(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

export function monthNames(style: "short" | "long" = "short"): string[] {
  const f = new Intl.DateTimeFormat(lang, { month: style, timeZone: "UTC" });
  return Array.from({ length: 12 }, (_, m) => {
    const s = f.format(new Date(Date.UTC(2001, m, 15))).replace(".", "");
    return s[0].toUpperCase() + s.slice(1);
  });
}

/** Idioma inicial: ?lang= > preferencia guardada > español. */
export function detectLang(search: string, stored: string | null): Lang {
  const q = new URLSearchParams(search).get("lang");
  if (q === "es" || q === "en") return q;
  return stored === "en" || stored === "es" ? stored : "es";
}
